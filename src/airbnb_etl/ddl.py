def sql_type(dialect: str, kind: str) -> str:
    varchar = "NVARCHAR" if dialect == "azure_sql" else "VARCHAR"
    decimal = "DECIMAL" if dialect == "azure_sql" else "NUMERIC"
    text = {
        "postgresql": "TEXT",
        "mysql": "LONGTEXT",
        "azure_sql": "NVARCHAR(MAX)",
    }[dialect]
    boolean = {
        "postgresql": "BOOLEAN",
        "mysql": "TINYINT(1)",
        "azure_sql": "BIT",
    }[dialect]
    timestamp = {
        "postgresql": "TIMESTAMPTZ",
        "mysql": "DATETIME(6)",
        "azure_sql": "DATETIME2",
    }[dialect]
    json_type = {
        "postgresql": "JSONB",
        "mysql": "JSON",
        "azure_sql": "NVARCHAR(MAX)",
    }[dialect]
    if kind in {"code", "label", "title", "short", "status", "run_id"}:
        return f"{varchar}({VARCHAR_LIMITS[kind]})"
    if kind == "sha":
        if dialect == "azure_sql":
            return f"{varchar}(64)"
        return "CHAR(64)"
    return {
        "text": text,
        "bigint": "BIGINT",
        "int": "INTEGER" if dialect == "postgresql" else "INT",
        "bool": boolean,
        "date": "DATE",
        "money": f"{decimal}(14,2)",
        "rate": f"{decimal}(6,2)",
        "score": f"{decimal}(5,2)",
        "coord": f"{decimal}(9,6)",
        "baths": f"{decimal}(4,1)",
        "occupancy": f"{decimal}(10,2)",
        "share": f"{decimal}(7,4)",
        "metric": f"{decimal}(8,2)",
        "revenue": f"{decimal}(16,2)",
        "json": json_type,
        "ts": timestamp,
    }[kind]


def split_sql(script: str) -> list[str]:
    """Split a dialect script on semicolon-terminated lines. Drops comment lines."""
    statements: list[str] = []
    buffer: list[str] = []
    for line in script.splitlines():
        if line.strip().startswith("--") or line.strip() == "GO":
            continue
        buffer.append(line)
        if line.strip().endswith(";"):
            statement = "\n".join(buffer).strip()
            if statement.endswith(";"):
                statement = statement[:-1].strip()
            if statement:
                statements.append(statement)
            buffer = []
    tail = "\n".join(buffer).strip()
    if tail:
        statements.append(tail)
    return statements


def _column_sql(dialect: str, column: Column) -> str:
    nullability = "NULL" if column.nullable else "NOT NULL"
    return f"  {column.name} {sql_type(dialect, column.kind)} {nullability}"


def _table_body(dialect: str, table: Table) -> str:
    lines = [_column_sql(dialect, column) for column in table.columns]
    pk_cols = ", ".join(table.primary_key)
    clustered = " CLUSTERED" if dialect == "azure_sql" else ""
    lines.append(
        f"  CONSTRAINT pk_{table.name} PRIMARY KEY{clustered} ({pk_cols})"
    )
    for name, column, target in table.foreign_keys:
        lines.append(f"  CONSTRAINT {name} FOREIGN KEY ({column}) REFERENCES {target}")
    return ",\n".join(lines)


def _create_table(dialect: str, table: Table) -> str:
    body = _table_body(dialect, table)
    if dialect == "postgresql":
        return f"CREATE TABLE IF NOT EXISTS {table.name} (\n{body}\n);"
    if dialect == "mysql":
        return (
            f"CREATE TABLE IF NOT EXISTS {table.name} (\n{body}\n) "
            "ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;"
        )
    return (
        f"IF OBJECT_ID(N'dbo.{table.name}', N'U') IS NULL\n"
        "BEGIN\n"
        f"  CREATE TABLE dbo.{table.name} (\n{body}\n  );\n"
        "END;"
    )


def _create_index(dialect: str, table: str, name: str, columns: tuple[str, ...]) -> str:
    cols = ", ".join(columns)
    if dialect == "postgresql":
        return f"CREATE INDEX IF NOT EXISTS {name} ON {table} ({cols});"
    if dialect == "azure_sql":
        return (
            "IF NOT EXISTS (\n"
            "  SELECT 1 FROM sys.indexes\n"
            f"  WHERE name = N'{name}' AND object_id = OBJECT_ID(N'dbo.{table}')\n"
            ")\n"
            "BEGIN\n"
            f"  CREATE INDEX {name} ON dbo.{table} ({cols});\n"
            "END;"
        )
    # MySQL has no CREATE INDEX IF NOT EXISTS. Prepare/execute keeps the script rerunnable.
    create = f"CREATE INDEX {name} ON {table} ({cols})"
    return (
        "SET @airbnb_index_exists := (\n"
        "  SELECT COUNT(*) FROM information_schema.statistics\n"
        "  WHERE table_schema = DATABASE()\n"
        f"    AND table_name = '{table}'\n"
        f"    AND index_name = '{name}'\n"
        ");\n"
        "SET @airbnb_index_sql := IF(\n"
        "  @airbnb_index_exists = 0,\n"
        f"  '{create}',\n"
        "  'SELECT 1'\n"
        ");\n"
        "PREPARE airbnb_index_stmt FROM @airbnb_index_sql;\n"
        "EXECUTE airbnb_index_stmt;\n"
        "DEALLOCATE PREPARE airbnb_index_stmt;"
    )


def _superhost_expr(dialect: str, qualifier: str = "") -> str:
    column = f"{qualifier}host_is_superhost"
    if dialect == "postgresql":
        return (
            f"CASE WHEN {column} IS TRUE THEN 1.0 "
            f"WHEN {column} IS FALSE THEN 0.0 END"
        )
    return f"CASE WHEN {column} = 1 THEN 1.0 WHEN {column} = 0 THEN 0.0 END"


def _create_view(dialect: str) -> str:
    share = _superhost_expr(dialect)
    select = f"""SELECT
  market_code,
  snapshot_date,
  COUNT(*) AS listings,
  AVG(price) AS avg_price,
  AVG(review_scores_rating) AS avg_rating,
  AVG({share}) AS superhost_share,
  SUM(estimated_revenue_l365d) AS estimated_revenue,
  AVG(estimated_occupancy_l365d) AS avg_occupancy,
  AVG(availability_365) AS avg_availability_365
FROM listings
GROUP BY market_code, snapshot_date"""
    if dialect == "postgresql":
        return f"CREATE OR REPLACE VIEW market_metrics AS\n{select};"
    if dialect == "mysql":
        return f"CREATE OR REPLACE VIEW market_metrics AS\n{select};"
    return f"CREATE OR ALTER VIEW dbo.market_metrics AS\n{select};"


def render_schema(dialect: str) -> str:
    if dialect not in DIALECTS:
        raise KeyError(dialect)
    parts = [HEADER.rstrip(), ""]
    for table in TABLES.values():
        parts.append(_create_table(dialect, table))
        parts.append("")
    for table in TABLES.values():
        for name, columns in table.indexes:
            parts.append(_create_index(dialect, table.name, name, columns))
            parts.append("")
    if dialect == "azure_sql":
        parts.append("GO")
        parts.append("")
    parts.append(_create_view(dialect))
    parts.append("")
    return "\n".join(parts)


def render_mart(dialect: str) -> str:
    if dialect == "postgresql":
        body = (
            "-- Bound parameters, in order: market_code, snapshot_date on the delete,\n"
            "-- then market_code, snapshot_date on the insert.\n"
            "-- Median price is an ordered-set aggregate, so it can sit next to GROUP BY.\n\n"
            f"{POSTGRES_DELETE_METRICS};\n\n"
            f"{POSTGRES_INSERT_METRICS};\n"
        )
    elif dialect == "mysql":
        body = _MYSQL_MART
    else:
        body = _AZURE_MART
    header = (
        "-- Generated by airbnb_etl.ddl. Do not edit by hand.\n"
        f"-- Dialect: {dialect}\n"
        "-- Rebuild neighbourhood_metrics for one city snapshot.\n"
        "-- Median is computed in the dialect that actually has the engine's function.\n\n"
    )
    return header + body


_MYSQL_MART = """\
SET @market = 'albany';
SET @snapshot = '2026-06-16';

DELETE FROM neighbourhood_metrics
WHERE market_code = @market AND snapshot_date = @snapshot;

INSERT INTO neighbourhood_metrics (
  market_code, snapshot_date, neighbourhood, listings,
  median_price, avg_price, avg_rating, superhost_share,
  avg_availability_365, estimated_revenue, avg_occupancy
)
SELECT
  agg.market_code,
  agg.snapshot_date,
  agg.neighbourhood,
  agg.listings,
  med.median_price,
  agg.avg_price,
  agg.avg_rating,
  agg.superhost_share,
  agg.avg_availability_365,
  agg.estimated_revenue,
  agg.avg_occupancy
FROM (
  SELECT
    market_code,
    snapshot_date,
    neighbourhood_cleansed AS neighbourhood,
    COUNT(*) AS listings,
    AVG(price) AS avg_price,
    AVG(review_scores_rating) AS avg_rating,
    AVG(CASE WHEN host_is_superhost = 1 THEN 1.0 WHEN host_is_superhost = 0 THEN 0.0 END)
      AS superhost_share,
    AVG(availability_365) AS avg_availability_365,
    SUM(estimated_revenue_l365d) AS estimated_revenue,
    AVG(estimated_occupancy_l365d) AS avg_occupancy
  FROM listings
  WHERE market_code = @market
    AND snapshot_date = @snapshot
    AND neighbourhood_cleansed IS NOT NULL
    AND neighbourhood_cleansed <> ''
  GROUP BY market_code, snapshot_date, neighbourhood_cleansed
) AS agg
LEFT JOIN (
  SELECT neighbourhood, AVG(price) AS median_price
  FROM (
    SELECT
      neighbourhood_cleansed AS neighbourhood,
      price,
      ROW_NUMBER() OVER (PARTITION BY neighbourhood_cleansed ORDER BY price) AS rn,
      COUNT(*) OVER (PARTITION BY neighbourhood_cleansed) AS cnt
    FROM listings
    WHERE market_code = @market
      AND snapshot_date = @snapshot
      AND price IS NOT NULL
      AND neighbourhood_cleansed IS NOT NULL
      AND neighbourhood_cleansed <> ''
  ) AS ranked
  WHERE rn IN (FLOOR((cnt + 1) / 2), FLOOR((cnt + 2) / 2))
  GROUP BY neighbourhood
) AS med ON med.neighbourhood = agg.neighbourhood;
"""

_AZURE_MART = """\
DECLARE @market NVARCHAR(64) = N'albany';
DECLARE @snapshot DATE = '2026-06-16';

DELETE FROM dbo.neighbourhood_metrics
WHERE market_code = @market AND snapshot_date = @snapshot;

WITH priced AS (
  SELECT
    market_code,
    snapshot_date,
    neighbourhood_cleansed,
    PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY price) OVER (
      PARTITION BY market_code, snapshot_date, neighbourhood_cleansed
    ) AS median_price
  FROM dbo.listings
  WHERE market_code = @market
    AND snapshot_date = @snapshot
    AND price IS NOT NULL
    AND neighbourhood_cleansed IS NOT NULL
    AND neighbourhood_cleansed <> N''
),
medians AS (
  SELECT DISTINCT
    market_code,
    snapshot_date,
    neighbourhood_cleansed,
    median_price
  FROM priced
)
INSERT INTO dbo.neighbourhood_metrics (
  market_code, snapshot_date, neighbourhood, listings,
  median_price, avg_price, avg_rating, superhost_share,
  avg_availability_365, estimated_revenue, avg_occupancy
)
SELECT
  listings.market_code,
  listings.snapshot_date,
  listings.neighbourhood_cleansed,
  COUNT(*),
  MAX(medians.median_price),
  AVG(listings.price),
  AVG(listings.review_scores_rating),
  AVG(CASE
    WHEN listings.host_is_superhost = 1 THEN 1.0
    WHEN listings.host_is_superhost = 0 THEN 0.0
  END),
  AVG(listings.availability_365),
  SUM(listings.estimated_revenue_l365d),
  AVG(listings.estimated_occupancy_l365d)
FROM dbo.listings AS listings
LEFT JOIN medians
  ON medians.market_code = listings.market_code
 AND medians.snapshot_date = listings.snapshot_date
 AND medians.neighbourhood_cleansed = listings.neighbourhood_cleansed
WHERE listings.market_code = @market
  AND listings.snapshot_date = @snapshot
  AND listings.neighbourhood_cleansed IS NOT NULL
  AND listings.neighbourhood_cleansed <> N''
GROUP BY
  listings.market_code,
  listings.snapshot_date,
  listings.neighbourhood_cleansed;
"""


def write_sql_files(root: Path) -> None:
    for dialect in DIALECTS:
        folder = root / dialect
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "schema.sql").write_text(render_schema(dialect), encoding="utf-8")
        (folder / "marts.sql").write_text(render_mart(dialect), encoding="utf-8")


def main() -> None:
    from airbnb_etl.config import project_root

    destination = project_root() / "sql"
    write_sql_files(destination)
    print(f"wrote SQL for {', '.join(DIALECTS)} under {destination}")


if __name__ == "__main__":
    main()
