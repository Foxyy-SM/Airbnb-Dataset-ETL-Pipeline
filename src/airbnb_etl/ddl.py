@dataclass(frozen=True)
class Column:
    name: str
    kind: str
    nullable: bool = True


@dataclass(frozen=True)
class Table:
    name: str
    columns: tuple[Column, ...]
    primary_key: tuple[str, ...]
    indexes: tuple[tuple[str, tuple[str, ...]], ...] = ()
    foreign_keys: tuple[tuple[str, str, str], ...] = ()


def _cols(*items: tuple[str, str] | tuple[str, str, bool]) -> tuple[Column, ...]:
    columns = []
    for item in items:
        if len(item) == 2:
            columns.append(Column(item[0], item[1], True))
        else:
            columns.append(Column(item[0], item[1], item[2]))
    return tuple(columns)


